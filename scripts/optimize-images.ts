/**
 * Converts assets/raw/ images to WebP in public/images/brand/ and
 * regenerates src/lib/brand-images.ts.
 *
 *   pnpm images [--force]
 *
 * Requires cwebp: brew install webp
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const RAW_DIR = path.join(process.cwd(), "assets", "raw");
const OUT_DIR = path.join(process.cwd(), "public", "images", "brand");
const QUALITY = 82;
const MAX_WIDTH = 1600;
const force = process.argv.includes("--force");

/** Hand-picked names; anything else falls back to a slug of the filename. */
const RENAMES: Record<string, string> = {
  "tender-mehndi-hands-in-warm-light": "mehndi-hands",
  "sunlit-marigold-ritual-still-life": "marigold-garland",
  "emerald-and-gold-wedding-invitation-flat-lay": "wedding-invitation",
  "golden-hour-courtyard-stroll": "courtyard-stroll",
  "festive-mithai-exchange-in-a-warm-home": "mithai-exchange",
};

/** PNG/JPEG intrinsic width, read from the header. */
function readWidth(file: string): number | null {
  const fd = fs.openSync(file, "r");
  try {
    const head = Buffer.alloc(32);
    fs.readSync(fd, head, 0, 32, 0);

    if (head.subarray(0, 8).equals(Buffer.from("89504e470d0a1a0a", "hex"))) {
      return head.readUInt32BE(16);
    }

    if (head[0] === 0xff && head[1] === 0xd8) {
      const size = fs.statSync(file).size;
      const buf = Buffer.alloc(size);
      fs.readSync(fd, buf, 0, size, 0);
      let off = 2;
      while (off < size - 9) {
        if (buf[off] !== 0xff) { off++; continue; }
        const marker = buf[off + 1];
        const len = buf.readUInt16BE(off + 2);
        if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
          return buf.readUInt16BE(off + 7);
        }
        off += 2 + len;
      }
    }
    return null;
  } finally {
    fs.closeSync(fd);
  }
}

const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/\.[^.]+$/, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

function ensureCwebp() {
  try {
    execFileSync("cwebp", ["-version"], { stdio: "ignore" });
  } catch {
    console.error("cwebp not found. Install it with:  brew install webp");
    process.exit(1);
  }
}

function main() {
  ensureCwebp();
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const sources = fs
    .readdirSync(RAW_DIR)
    .filter((f) => /\.(png|jpe?g|webp|tiff?)$/i.test(f))
    .sort();

  if (sources.length === 0) {
    console.log("No images in assets/raw/ — nothing to do.");
    return;
  }

  let converted = 0;
  let skipped = 0;

  for (const file of sources) {
    const slug = slugify(file);
    const name = RENAMES[slug] ?? slug;
    const src = path.join(RAW_DIR, file);
    const out = path.join(OUT_DIR, `${name}.webp`);

    if (!force && fs.existsSync(out) && fs.statSync(out).mtimeMs >= fs.statSync(src).mtimeMs) {
      skipped++;
      continue;
    }

    // cwebp -resize upscales if asked, so clamp to the source width.
    const srcWidth = readWidth(src);
    const target = srcWidth ? Math.min(MAX_WIDTH, srcWidth) : MAX_WIDTH;
    const resize = srcWidth && srcWidth <= MAX_WIDTH ? [] : ["-resize", String(target), "0"];

    execFileSync("cwebp", [
      "-q", String(QUALITY),
      ...resize,
      "-metadata", "none",
      src,
      "-o", out,
    ], { stdio: "ignore" });

    const before = fs.statSync(src).size;
    const after = fs.statSync(out).size;
    const saved = Math.round((1 - after / before) * 100);
    console.log(
      `  ${file}\n    -> ${name}.webp  ${target}px  ${(before / 1e6).toFixed(1)}MB -> ${(after / 1e3).toFixed(0)}KB  (-${saved}%)`,
    );
    converted++;
  }

  writeManifest();
  console.log(`\nDone. ${converted} converted, ${skipped} up to date.`);
}

/** Static imports (not string paths) are what give next/image a blurDataURL. */
function writeManifest() {
  const files = fs
    .readdirSync(OUT_DIR)
    .filter((f) => f.endsWith(".webp"))
    .sort();

  const ident = (f: string) =>
    path.basename(f, ".webp").replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());

  const lines = [
    "// AUTO-GENERATED by scripts/optimize-images.ts — do not edit by hand.",
    "// Run `pnpm images` after adding files to assets/raw/.",
    "",
    ...files.map((f) => `import ${ident(f)} from "../../public/images/brand/${f}";`),
    "",
    "import type { StaticImageData } from \"next/image\";",
    "",
    "export type BrandImage = { src: StaticImageData; alt: string };",
    "",
    "/** Alt text per image. Unlisted files fall back to a generic caption. */",
    "const ALT: Record<string, string> = {",
    '  mehndiHands: "A couple\'s hands resting together, the bride\'s palms patterned with mehndi",',
    '  marigoldGarland: "A marigold and jasmine garland on a carved wooden table in afternoon light",',
    '  weddingInvitation: "An emerald and gold wedding invitation card on handmade paper",',
    '  courtyardStroll: "A couple walking through a sunlit courtyard in the late afternoon",',
    '  mithaiExchange: "Hands exchanging a tray of mithai in a warm family home",',
    "};",
    "",
    "export const BRAND_IMAGES: BrandImage[] = [",
    ...files.map(
      (f) =>
        `  { src: ${ident(f)}, alt: ALT.${ident(f)} ?? "Decorative wedding photograph" },`,
    ),
    "];",
    "",
  ];

  fs.writeFileSync(path.join(process.cwd(), "src", "lib", "brand-images.ts"), lines.join("\n"));
  console.log(`\n  manifest: src/lib/brand-images.ts (${files.length} images)`);
}

main();
